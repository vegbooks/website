      <p>{"This book is definitely a great introduction to the issues involved in eating sentient beings. Gemma refuses to eat chicken and Andrew stops as well until he knows exactly where and how the chicken was raised. But for the vegan in me, the endorsement of the welfare argument was a sore point. Fine even has the chicken offering up one of her eggs to the aliens to eat. She also occasionally portrays the chicken as a self-deprecating animal (calling herself feather-brained and chicken-dippy), which really irked me since "}<a href={"http://www.upc-online.org/thinking/social_life_of_chickens.html"}>{"I know they are far from it"}</a>{". But I will say that this book will prepare your little vegan for all the lame arguments he or she will undoubtedly hear from meat eaters on justifying their dietary choices (“I know they squawk and fuss and rattle the cage bars, trying to get out. But, honestly, they don’t mind, really. You see, they’re not nearly as sensitive as we are!”)"}</p>
