      <p>{"Although I like the message about getting rid of stuff that we don’t use or need, I struggled with the fantasy that it’s so easy to part with the clutter that fills up our own homes. And that’s not even touching on the deeper psychological issues of anxiety, depression, or obsessive compulsiveness linked to acquiring and "}<a href={"http://en.wikipedia.org/wiki/Compulsive_hoarding"} target="_blank" rel="noopener noreferrer">{"compulsive hoarding"}</a>{". Understandably this is a children’s fiction story which highlights the altruistic reasons for giving up extra toys and clothes. However, it barely touches on the concern of materialism in our commercial society, how to deal with limiting what we purchase, and never mentions "}<a href={"http://www.sciencedaily.com/releases/2004/12/041219182811.htm"} target="_blank" rel="noopener noreferrer">{"happiness in terms of experiences versus posessions"}</a>{". If we reduce the amount we purchase, there would be less stuff we need to deal with or get rid of. I also felt some of the title was misleading because recycling was given a bit role in the story and nothing was mentioned about "}<a href={"http://www.epa.gov/osw/conserve/rrr/reduce.htm"} target="_blank" rel="noopener noreferrer">{"reducing"}</a>{" the amount of trash and toxicity we buy/create. The issue of hoarding/discarding “stuff” was primary but there was no information about the support that enables a person to deal with hoarding issues."}</p>
