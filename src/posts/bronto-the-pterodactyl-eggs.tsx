      <p>{"The prose is simple enough for the 4 and up age group it is aimed at but it also respects that children will want to know the proper names for dinosaurs and even the molten lava that erupts from the volcano. From the pacing and author biography sharing that the story was originally one told with puppets, you can tell the text was well honed before the illustration stage. My daughter was concerned when the volcano erupted but was happy to see that everyone was okay in the end, proclaiming that the “hot lava” was her favorite part. We talked about why Bronto would bury the eggs and run for safety instead of taking them with him and she speculated (incorrectly) that Bronto was the eggs’ father and their mother was absent. I can see where she would get the idea from the dream illustrations when Bronto has wings and is flying. We enjoyed reading and discussing the book."}</p>
