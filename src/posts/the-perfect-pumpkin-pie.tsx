      <p>{"The author Denys Cazet doesn’t pull any punches when he also addresses death in the second page of the book. Being so used to skirting around talk of aging and death in our society, it was a shocker to have Old Man Wilkerson state “Then I AIN’T GOIN’!” if there’s no more pie after we die. And of course, then he dies, dramatically keeling over into his beloved pie, still grasping his fork. Even if we don’t like Wilkerson, we can all relate to not wanting to die because there are pies we want to enjoy. We are so used to avoiding the topic of death, though, and we often fear it, so we rarely address it with our kids until they have experienced a loss. I was hesitant to read this to my child even though we had discussed death when we lost our beloved family dog this year. But I decided avoiding it was like hiding it in a dark closet, making it an unknown and even more scary than if it was brought out in the open to learn about it, address it, and lose our fear of it. And honestly, the topic of death didn’t even come up with all the various entertaining elements of the story. But Grandma’s pretty smart because fear is “nothing but cold smoke.” And Cazet is pretty clever to incorporate such weighty topics so casually in a children’s story and lightening it by having ornery Wilkerson come back to enjoy some more pie as a ghost every Halloween."}</p>
